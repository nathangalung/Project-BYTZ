/**
 * Which facts a scoping conversation has to establish before a BRD is worth
 * generating, who supplies each one, and what to ask when it is absent.
 *
 * This file is the denominator of the completeness percentage, the list the
 * chatbot asks from, and the boundary between what the owner is asked for and
 * what the platform derives. All three read the same table so they cannot
 * describe different gaps.
 *
 * The governing assumption: a project owner is a business stakeholder, not a
 * technologist. Every scored field must be answerable by someone who has never
 * chosen a framework. Anything technical is derived at PRD time and never
 * scored, so a fully cooperative owner reaches 100 without naming a single
 * piece of technology. `owner_answerable.test.ts` asserts that property.
 *
 * Keys are i18n suffixes behind the "still needed" chips (missing_problem,
 * missing_budget) and the question prompts, so renaming one is a UI change.
 *
 * The Python copy is generated by apps/ai-service/scripts/generate-completeness.ts
 * and CI fails when the checked-in output no longer matches this file.
 */

/** Where a field's answer comes from. */
export type ScopingFieldSource = 'form' | 'chat'

/** Which document the field is a prerequisite for. */
export type ScopingFieldStage = 'brd' | 'prd'

export type ScopingField = {
  readonly key: string
  readonly source: ScopingFieldSource
  readonly stage: ScopingFieldStage
  /**
   * Degrade path only. Extraction over the transcript decides coverage; these
   * words decide it when extraction is unavailable. A form field has none
   * because reading the column cannot fail in a way words would rescue.
   */
  readonly fallbackKeywords: readonly string[]
}

