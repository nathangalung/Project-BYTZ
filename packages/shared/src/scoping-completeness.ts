/**
 * Minimum length of the project description before it counts as one.
 *
 * Measured over the description column alone, not the joined transcript. The
 * previous 80 was satisfied by any 80 characters anywhere in the conversation,
 * which made the check pass before the owner had described anything.
 */
export const DESCRIPTION_MIN_CHARS = 120

/**
 * Score at which the Generate BRD control is enabled.
 *
 * Eleven BRD fields, so the grain is about nine points and 82 is the first
 * value reachable with nine of eleven covered. The old 80 was a fraction of a
 * different denominator and is not carried across unchanged: it now means the
 * owner may leave at most two of the eleven unanswered, and the two it can
 * absorb are the ones a BRD survives without.
 */
export const BRD_READY_SCORE = 82
